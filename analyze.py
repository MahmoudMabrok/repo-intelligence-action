#!/usr/bin/env python3
"""Lightweight repository intelligence analyzer for GitHub Actions.

Collects LOC (via scc), git stats (including span in days), README check,
optional secret scan, AI-agent signals, and acceptance gates. Writes report.json.
"""

import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


AI_FILE_PATTERNS = (
    ".cursor", ".cursorrules", "AGENTS.md", "CLAUDE.md", "COPILOT.md",
    ".github/copilot-instructions.md", ".github/instructions",
    ".aider", ".aider.conf.yml", ".windsurf", ".continue",
    ".clinerules", "GEMINI.md", ".roo",
)

AI_COMMIT_KEYWORDS = re.compile(
    r"\b(copilot|cursor|claude|gpt-?4|chatgpt|openai|anthropic|aider|windsurf|"
    r"generated by|ai[- ]generated|llm|co-authored-by:\s*(copilot|cursor|claude))\b",
    re.I,
)

AI_CODE_MARKERS = re.compile(
    r"(generated by|ai[- ]generated|copilot|cursor ai|claude|chatgpt|"
    r"# noqa: ai|# generated|// generated by)",
    re.I,
)

SOURCE_EXTS = {
    ".py", ".js", ".ts", ".tsx", ".jsx", ".go", ".java", ".kt", ".rs",
    ".rb", ".php", ".c", ".cpp", ".h", ".cs", ".swift", ".scala", ".md",
}


def run(cmd, check=True, capture=True):
    result = subprocess.run(
        cmd,
        check=False,
        capture_output=capture,
        text=True,
    )
    if check and result.returncode != 0:
        print(result.stderr or result.stdout, file=sys.stderr)
        raise SystemExit(result.returncode)
    return result


def scc_summary():
    """Return total code lines and file count from scc JSON."""
    result = run(["scc", "--format", "json", "."], check=False)
    if result.returncode != 0:
        print("scc failed, falling back to zeros", file=sys.stderr)
        return 0, 0, {}
    try:
        data = json.loads(result.stdout or "[]")
    except json.JSONDecodeError:
        return 0, 0, {}
    total_code = 0
    total_files = 0
    by_lang = {}
    if isinstance(data, list):
        for item in data:
            code = int(item.get("Code", 0) or 0)
            files = int(item.get("Count", 0) or 0)
            total_code += code
            total_files += files
            name = item.get("Name") or "Unknown"
            by_lang[name] = {"code": code, "files": files}
    return total_code, total_files, by_lang


def git_stats():
    """Return commits, contributors, span in days and months, plus AI commit signals."""
    commits = 0
    contributors = 0
    span_days = 0
    span_months = 0.0
    first = None
    last = None
    ai_commits = 0
    ai_authors = set()
    sample_ai_messages = []

    log = run(
        ["git", "log", "--pretty=format:%aI|%aN|%s", "--all"],
        check=False,
    )
    if log.returncode != 0 or not log.stdout.strip():
        return {
            "commits": 0, "contributors": 0, "span_days": 0, "span_months": 0.0,
            "first": None, "last": None, "ai_commits": 0, "ai_authors": [],
            "ai_commit_samples": [],
        }

    authors = set()
    dates = []
    for line in log.stdout.splitlines():
        parts = line.split("|", 2)
        if len(parts) < 3:
            continue
        date_s, author, subject = parts
        authors.add(author.strip())
        try:
            dates.append(datetime.fromisoformat(date_s.replace("Z", "+00:00")))
        except ValueError:
            pass
        if AI_COMMIT_KEYWORDS.search(subject) or AI_COMMIT_KEYWORDS.search(author):
            ai_commits += 1
            ai_authors.add(author.strip())
            if len(sample_ai_messages) < 8:
                sample_ai_messages.append(subject[:160])

    commits = len(log.stdout.splitlines())
    contributors = len(authors)
    if dates:
        first = min(dates)
        last = max(dates)
        delta = last - first
        span_days = max(delta.days, 0)
        span_months = round(delta.days / 30.44, 1)

    return {
        "commits": commits,
        "contributors": contributors,
        "span_days": span_days,
        "span_months": span_months,
        "first": first.isoformat() if first else None,
        "last": last.isoformat() if last else None,
        "ai_commits": ai_commits,
        "ai_authors": sorted(ai_authors),
        "ai_commit_samples": sample_ai_messages,
    }


def readme_ok(min_chars=200):
    for name in ("README.md", "README.rst", "README.txt", "README"):
        p = Path(name)
        if p.is_file():
            text = p.read_text(errors="replace")
            return len(text.strip()) >= min_chars, len(text.strip()), name
    return False, 0, None


def secret_scan():
    """Run gitleaks if available. Returns finding count or None if skipped."""
    if os.environ.get("SCAN_SECRETS", "true").lower() not in ("1", "true", "yes"):
        return None
    result = run(
        ["gitleaks", "detect", "--source", ".", "--report-format", "json",
         "--report-path", "gitleaks-report.json", "--no-banner", "--exit-code", "0"],
        check=False,
    )
    report = Path("gitleaks-report.json")
    if report.is_file():
        try:
            findings = json.loads(report.read_text() or "[]")
            return len(findings) if isinstance(findings, list) else 0
        except json.JSONDecodeError:
            return 0
    return 0


def ai_file_signals():
    """Find AI-agent config files and marker hits in source."""
    found_files = []
    marker_files = []
    marker_hits = 0
    scanned_files = 0

    for pattern in AI_FILE_PATTERNS:
        p = Path(pattern)
        if p.exists():
            found_files.append(str(p))

    # Also walk for common AI config names
    for root, dirs, files in os.walk("."):
        # skip heavy dirs
        dirs[:] = [d for d in dirs if d not in {".git", "node_modules", "venv", ".venv", "dist", "build"}]
        for fname in files:
            rel = Path(root) / fname
            low = str(rel).lower().replace("\\", "/")
            if any(x in low for x in ("copilot", "cursor", "aider", "claude.md", "agents.md", ".cursorrules")):
                if str(rel) not in found_files:
                    found_files.append(str(rel))
            ext = Path(fname).suffix.lower()
            if ext not in SOURCE_EXTS:
                continue
            if scanned_files > 400:
                continue
            try:
                text = rel.read_text(errors="ignore")[:200_000]
            except OSError:
                continue
            scanned_files += 1
            hits = len(AI_CODE_MARKERS.findall(text))
            if hits:
                marker_hits += hits
                if len(marker_files) < 15:
                    marker_files.append(str(rel))

    return {
        "ai_config_files": sorted(set(found_files))[:30],
        "ai_marker_files": marker_files,
        "ai_marker_hits": marker_hits,
        "files_scanned_for_markers": scanned_files,
    }


def ai_analytics(git, file_signals, total_commits):
    """Combine signals into a simple AI-agent statistics block."""
    ai_commits = git["ai_commits"]
    ai_commit_pct = round(100.0 * ai_commits / total_commits, 1) if total_commits else 0.0
    has_config = len(file_signals["ai_config_files"]) > 0
    has_markers = file_signals["ai_marker_hits"] > 0

    # Heuristic confidence 0-100 based on signals (not a real detector)
    score = 0
    if has_config:
        score += 30
    score += min(40, ai_commit_pct)
    score += min(30, file_signals["ai_marker_hits"] * 5)
    score = int(min(100, score))

    if score >= 50:
        label = "likely"
    elif score >= 20:
        label = "possible"
    else:
        label = "low"

    return {
        "ai_commits": ai_commits,
        "ai_commit_percent": ai_commit_pct,
        "ai_authors": git["ai_authors"],
        "ai_commit_samples": git["ai_commit_samples"],
        "ai_config_files": file_signals["ai_config_files"],
        "ai_marker_hits": file_signals["ai_marker_hits"],
        "ai_marker_files": file_signals["ai_marker_files"],
        "files_scanned_for_markers": file_signals["files_scanned_for_markers"],
        "ai_signal_score": score,
        "ai_signal_label": label,
        "note": "Heuristic only (config files, commit keywords, code markers). Not a true AI-code detector.",
    }


def main():
    min_files = int(os.environ.get("MIN_SOURCE_FILES", "20"))
    min_loc = int(os.environ.get("MIN_LOC", "5000"))
    min_contrib = int(os.environ.get("MIN_CONTRIBUTORS", "2"))
    min_commits = int(os.environ.get("MIN_COMMITS", "100"))
    min_months = float(os.environ.get("MIN_MONTHS", "6"))
    require_readme = os.environ.get("REQUIRE_README", "true").lower() in ("1", "true", "yes")

    loc, source_files, by_lang = scc_summary()
    git = git_stats()
    has_readme, readme_chars, readme_name = readme_ok()
    secrets = secret_scan()
    file_signals = ai_file_signals()
    ai = ai_analytics(git, file_signals, git["commits"])

    failures = []
    if source_files < min_files:
        failures.append(f"source files {source_files} < {min_files}")
    if loc < min_loc:
        failures.append(f"LOC {loc} < {min_loc}")
    if git["contributors"] < min_contrib:
        failures.append(f"contributors {git['contributors']} < {min_contrib}")
    if git["commits"] < min_commits:
        failures.append(f"commits {git['commits']} < {min_commits}")
    if git["span_months"] < min_months:
        failures.append(f"span {git['span_months']} months < {min_months}")
    if require_readme and not has_readme:
        failures.append(f"README missing or shorter than 200 chars (got {readme_chars})")

    passed = len(failures) == 0

    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "repository": os.environ.get("GITHUB_REPOSITORY", ""),
        "ref": os.environ.get("GITHUB_REF", ""),
        "sha": os.environ.get("GITHUB_SHA", ""),
        "loc": loc,
        "source_files": source_files,
        "languages": by_lang,
        "commits": git["commits"],
        "contributors": git["contributors"],
        "span_days": git["span_days"],
        "span_months": git["span_months"],
        "first_commit": git["first"],
        "last_commit": git["last"],
        "readme": {"present": has_readme, "chars": readme_chars, "file": readme_name},
        "secret_findings": secrets,
        "ai_analytics": ai,
        "gates": {
            "min_source_files": min_files,
            "min_loc": min_loc,
            "min_contributors": min_contrib,
            "min_commits": min_commits,
            "min_months": min_months,
            "require_readme": require_readme,
        },
        "failures": failures,
        "passed": passed,
    }

    Path("report.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))

    github_output = os.environ.get("GITHUB_OUTPUT")
    if github_output:
        with open(github_output, "a") as f:
            f.write("report_path=report.json\n")
            f.write(f"passed={str(passed).lower()}\n")
            f.write(f"loc={loc}\n")
            f.write(f"span_days={git['span_days']}\n")
            f.write(f"ai_signal_score={ai['ai_signal_score']}\n")

    fail_on_gates = os.environ.get("FAIL_ON_GATES", "false").lower() in ("1", "true", "yes")
    if fail_on_gates and not passed:
        print("Acceptance gates failed", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
